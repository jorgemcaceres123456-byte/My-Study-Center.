export type ID = string;

export interface Subject {
  id: ID;
  name: string;
  color: string;
  icon: string;
  folder: string;
  createdAt: string;
}

export interface Task {
  id: ID;
  subjectId: ID;
  title: string;
  notes: string;
  done: boolean;
  priority: 'baja' | 'media' | 'alta';
  createdAt: string;
  completedAt?: string;
}

export type LibraryKind = 'image' | 'pdf' | 'docx' | 'xlsx' | 'pptx' | 'txt' | 'audio' | 'file';

/** Página de cuaderno subida desde "Fotos y apuntes". */
export interface StudyImage {
  id: ID;
  subjectId: ID | '';
  name: string;
  mime: string;
  size: number;
  createdAt: string;
  notes: string;
  tags: string[];
  /** Texto que la IA extrajo/recordó de esta página. Alimenta todos los chats. */
  aiSummary: string;
  /** IDB key of the binary blob. */
  blobKey: string;
  /** Se ha enviado a la IA (analizada o adjunta en el chat). */
  sentToAi: boolean;
}

/** Cualquier archivo enviado al chat (pdf, docx, imagen, audio, etc.). */
export interface ChatFile {
  id: ID;
  name: string;
  mime: string;
  size: number;
  kind: LibraryKind;
  blobKey: string;
  /** Texto extraído (o transcripción, en el caso de audio). */
  extractedText: string;
  createdAt: string;
  subjectId: ID | '';
  notes: string;
  durationSec?: number;
}

/** Recuerdo duradero generado al "absorber" una página. */
export interface Memory {
  id: ID;
  imageId: ID;
  blobKey: string;
  name: string;
  subjectId: ID | '';
  summary: string;
  createdAt: string;
}

/** Sesión de estudio REAL (cronómetro o registro manual). */
export interface StudySession {
  id: ID;
  subjectId: ID | '';
  /** yyyy-MM-dd local */
  day: string;
  startedAt: string;
  endedAt: string;
  durationSec: number;
  note: string;
  source: 'timer' | 'manual';
}

export interface ActiveSession {
  subjectId: ID | '';
  note: string;
  running: boolean;
  /** epoch ms de inicio del tramo actual */
  startedAt: number;
  /** segundos acumulados en tramos anteriores */
  accumulatedSec: number;
}

export type EventType = 'tarea' | 'examen' | 'proyecto' | 'recordatorio' | 'otro';

export interface CalendarEvent {
  id: ID;
  subjectId: ID | '';
  title: string;
  description: string;
  /** Local datetime, yyyy-MM-ddTHH:mm */
  date: string;
  type: EventType;
  reminders: number[];
  firedReminders: string[];
  done: boolean;
}

export interface Habit {
  id: ID;
  name: string;
  icon: string;
  color: string;
  goal: number;
  createdAt: string;
  dates: string[];
}

export interface AudioRef {
  id: ID;
  blobKey: string;
  name: string;
  mime: string;
  durationSec: number;
  transcript: string;
}

export interface ChatMessage {
  id: ID;
  role: 'user' | 'assistant';
  content: string;
  createdAt: string;
  error?: boolean;
  /** StudyImage ids attached to this user message. */
  attachments?: ID[];
  /** ChatFile ids attached to this user message. */
  fileIds?: ID[];
  /** Audio clips recorded/uploaded with this message. */
  audios?: AudioRef[];
  /** IDB key for an image generated by an image model. */
  imageKey?: string;
  /** Remote URL when the image provider returns a link instead of base64. */
  imageUrl?: string;
  pending?: boolean;
}

export type AIProvider = 'openrouter' | 'openai' | 'gemini' | 'custom';

export interface AISettings {
  provider: AIProvider;
  apiKey: string;
  baseUrl: string;
  model: string;
  temperature: number;
  vision: boolean;
  imageModel: string;
  /** Modelo de transcripción (endpoint /audio/transcriptions). */
  transcribeModel: string;
  /** Analizar automáticamente las fotos recién subidas. */
  autoAbsorb: boolean;
  /** Voz y velocidad del text-to-speech del navegador. */
  ttsRate: number;
  ttsVoice: string;
  persona: string;
}

export interface AppState {
  version: number;
  subjects: Subject[];
  tasks: Task[];
  images: StudyImage[];
  chatFiles: ChatFile[];
  memories: Memory[];
  sessions: StudySession[];
  activeSession: ActiveSession | null;
  events: CalendarEvent[];
  habits: Habit[];
  messages: ChatMessage[];
  pentagonSubjectIds: ID[];
  settings: AISettings;
  accent: 'aurora' | 'ocean' | 'sunset';
  notificationsEnabled: boolean;
  seeded: boolean;
}

export type SectionId =
  | 'dashboard'
  | 'subjects'
  | 'library'
  | 'biblioteca'
  | 'chat'
  | 'sessions'
  | 'calendar'
  | 'habits'
  | 'settings';
